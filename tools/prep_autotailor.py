"""Daily auto-tailor PREP (no LLM, no cost): pick the review-visible roles that pass the
guardrails, write their tailoring prompts, and emit a manifest for the headless Claude Code
step to work through. Prints how many were queued (0 => the shell wrapper skips the LLM step).

With `application_budget` on (the default since 2026-07-30) the guardrail is simply "is it in
today's review queue" — budget.select_daily already applied binary eligibility, the per-company
stock cap, strict-company pacing, and the daily bucket mix. The legacy score gate
(auto_tailor.min_score) is only used when application_budget.enabled is false.
"""
import json
import sys
from collections import Counter

sys.path.insert(0, ".")
from app import budget, config as cfgmod, store, tailoring  # noqa: E402
from app import pace as pacemod

MANIFEST = "scratch_priors/autotailor_manifest.json"


def manifest_path(cfg: dict) -> str:
    """Per-workspace manifest (config auto_tailor.manifest) so two candidates' nightly batches
    never overwrite each other's job list."""
    return str((cfg.get("auto_tailor") or {}).get("manifest") or MANIFEST)


def main():
    cfg = cfgmod.load_config()
    at = cfg.get("auto_tailor") or {}
    if not at.get("enabled"):
        print("auto_tailor disabled"); _write([], cfg); return
    conn = store.connect_view(cfg)

    if budget.enabled(cfg):
        # Contract (owner 2026-07-30): "what the review queue shows me today is what should
        # have a résumé today". No score gate at all — application_budget already decided
        # eligibility (binary) and volume, so re-gating on score here would reintroduce
        # exactly the bug we removed: a 66-point role at a company with zero applications is
        # worth more than Nvidia's 14th 78-point role.
        #
        # FULL BATCH POLICY (owner 2026-09-13: 「找新岗位之后自动触发 tailor,不要把他们分开
        # 做」). One-lead-per-company (2026-07-31) left the long tail to manual batch runs —
        # she had to ask for a catch-up batch two days in a row. The chained daily run now
        # applies the standing batch policy directly (see jobscan-batch-tailor-cap 拍板,
        # 2026-09-09): strong/consider/weak all count (drop never), signature-deduped, and
        # each company gets its TOP-20 roles by score — ready ones count toward the 20, so a
        # fully-covered company consumes no batch slots. auto_tailor.sh runs the headless
        # sessions 4-way parallel so an 80-role day still finishes.
        d = store.fetch_view(conn, cfg, status="new")
        pool = [r for r in d["rows"] if r.get("verdict") in ("strong", "consider", "weak")]
        best: dict = {}
        for r in sorted(pool, key=lambda r: r.get("weighted_score") or 0, reverse=True):
            best.setdefault((r["company_norm"], r["title_norm"]), r)
        per_co: Counter = Counter()
        picks = []
        for r in sorted(best.values(), key=lambda r: r.get("weighted_score") or 0, reverse=True):
            if per_co[r["company_norm"]] >= 20:
                continue
            per_co[r["company_norm"]] += 1
            picks.append(r)
        todo = [r for r in picks if r.get("tailor_status") != "ready"]
        # Credibility cutover (2026-08-06): résumés generated by the old pipeline are stale
        # (keyword-stuffed, sometimes fabricated). Owner's call: don't batch-regenerate the
        # backlog — refresh stale ones ON DEMAND as they surface at the top of the apply
        # queue, capped per run so the headless batch stays finishable. Queue order = the
        # order she works top-down, so the cap always refreshes what she'll apply to next.
        #
        # The cap is on the TOTAL, not on the stale add-on (2026-08-10). Capping only the
        # add-on made it a ratchet that bound on run 1 and never again: write_prompt()'s last
        # act is set_tailor(tailor_status="queued"), so the 25 stale roles picked this run stop
        # being `ready`, and on the next run they match the *uncapped* "not ready" line above
        # instead. Any batch the headless run doesn't finish rolls forward on top of 25 fresh
        # stale ones — 30, then 43, then worse — which is the exact outcome the cap exists to
        # prevent. Measured today: 0 never-tailored leads and 410 ready ones, so a total cap
        # costs nothing now and bounds the runaway later.
        # `auto_tailor.batch_cap` overrides if the total ever needs to be bigger than the
        # stale allowance (e.g. a day with many never-tailored companies); it defaults to
        # stale_refresh_cap so no config change is required for this fix to take effect.
        refresh_cap = int(at.get("batch_cap", at.get("stale_refresh_cap", 25)))
        base = tailoring.load_base(cfg)          # hoisted: resume_is_stale now reads content
        fresh_ids = {r["job_id"] for r in todo}
        stale = [r for r in picks
                 if r.get("tailor_status") == "ready" and r["job_id"] not in fresh_ids
                 and tailoring.resume_is_stale(cfg, r["company"], r["job_id"], base)]
        # Never-tailored roles keep priority over refreshes — they have no résumé at all.
        todo = (todo + stale)[:refresh_cap]
        cap = refresh_cap
    else:
        min_score = float(at.get("min_score", 75))
        strong_min = float(at.get("strong_min_score", 70))
        cap = int(at.get("max_per_day", 30))
        d = store.fetch_view(conn, cfg, status="all")
        todo = [r for r in d["rows"]
                if r.get("in_review")
                and r.get("tailor_status") != "ready" and r.get("verdict") != "drop"
                and ((r["weighted_score"] or 0) >= min_score
                     or (r.get("verdict") == "strong"
                         and (r["weighted_score"] or 0) >= strong_min))]
        todo.sort(key=lambda r: -r.get("rank_score", r["weighted_score"] or 0))
        todo = todo[:cap]

    # 投递节奏 (owner 2026-09-28, app/pace.py). Sprint → allow is None and nothing below runs, so
    # the full-batch policy above is untouched. Any other level replaces the batch with: today's
    # frozen review list first (so every row she sees has a résumé), then the next companies in
    # the same order (tomorrow's likely list), never-tailored and stale ones only, capped by what
    # is left of today's résumé allowance. Pause → allow 0 → empty manifest.
    allow = pacemod.tailor_allowance(conn, cfg)
    today = store.la_today()
    scanned_today = conn.execute("SELECT 1 FROM jobs.scan_runs WHERE substr(run_at,1,10)=? LIMIT 1",
                                 (today,)).fetchone() is not None
    if allow is not None and not scanned_today:
        # The 08:20 LinkedIn job chains this script before the 09:00 ATS scan. Spending today's
        # allowance on the pre-scan queue would leave the morning round's (freshest) roles
        # without résumés; the post-scan run does the day's batch instead.
        print("投递节奏: today's first ATS scan hasn't finished yet — leaving the batch to the post-scan run")
        todo, cap = [], allow
    elif allow is not None:
        pacemod.prune(conn)
        # Never be the one that freezes the day's list: the settings page promises it happens
        # when she first opens review. Before that, the unpaced queue's first N companies ARE
        # what the freeze will pick (same diversity order, rot 0), so read them without writing.
        full = store.fetch_view(conn, cfg, status="new")["rows"]
        if pacemod.has_freeze(conn, today):
            today_rows = store.fetch_view(conn, cfg, status="new", pace=True)["rows"]
        else:
            today_rows = []
        seen_co = {r["company_norm"] for r in today_rows}
        seq = list(today_rows)
        for r in full:                       # lead role of each further company, queue order
            if r["company_norm"] not in seen_co and r.get("verdict") != "drop":
                seen_co.add(r["company_norm"])
                seq.append(r)
        base = tailoring.load_base(cfg)
        todo = []
        for r in seq:
            if len(todo) >= allow:
                break
            if r.get("tailor_status") != "ready" or tailoring.resume_is_stale(
                    cfg, r["company"], r["job_id"], base):
                todo.append(r)
        cap = allow
        eff = pacemod.effective(conn, cfg)
        print(f"投递节奏 {eff['label']}: {allow} résumé(s) left today; today's list {len(today_rows)} "
              f"row(s); queuing {len(todo)}")

    manifest = []
    for r in todo:
        try:
            p = tailoring.write_prompt(cfg, conn, r["job_id"])
            out = tailoring.resume_yaml_path(cfg, r["company"], r["job_id"])
            manifest.append({"job_id": r["job_id"], "company": r["company"], "title": r["title"],
                             "prompt": str(p), "resume_out": str(out), "score": r["weighted_score"]})
        except Exception as e:  # noqa: BLE001
            print(f"  skip {r['job_id']}: {e}", file=sys.stderr)
    _write(manifest, cfg)
    if allow is not None:
        pacemod.log_tailored(conn, [m["job_id"] for m in manifest])
    gate = "budget: today's review queue" if budget.enabled(cfg) else f"score>={min_score:g}"
    print(f"auto_tailor prep: {len(manifest)} roles queued ({gate}, cap {cap})")


def _write(manifest, cfg=None):
    out = cfgmod.resolve_path(manifest_path(cfg or {}))
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(manifest, indent=1), encoding="utf-8")


if __name__ == "__main__":
    main()
